import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const migration = await readFile(new URL('../supabase/migrations/20261031232711_ladra_feed_compartido.sql', import.meta.url), 'utf8');
test('Feed real: propiedad, edición, privacidad, historias de 24 h y aislamiento de archivos', async () => {
  const db = new PGlite();
  const owner = '00000000-0000-0000-0000-000000000001', other = '00000000-0000-0000-0000-000000000002';
  const pet = '10000000-0000-0000-0000-000000000001', privatePet = '10000000-0000-0000-0000-000000000002';
  const scalar = async (sql, args = []) => Object.values((await db.query(sql, args)).rows[0] || {})[0];
  const as = async (role, user = '') => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [user]); await db.exec('set role ' + role); };
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth; create schema ladra; create schema storage;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      create table ladra.animales(id uuid primary key,creado_por uuid,estado text default 'publicado',mostrar_en_red boolean default true);
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text);
      create function storage.foldername(text) returns text[] language sql immutable as $$select (string_to_array($1,'/'))[1:array_length(string_to_array($1,'/'),1)-1]$$;
      grant usage on schema auth,ladra,storage to anon,authenticated; grant select on ladra.animales to anon,authenticated;
      grant select,insert,update,delete on storage.objects to authenticated; alter table storage.objects enable row level security;
      create policy legacy_select on storage.objects for select using(true);
      create policy legacy_insert on storage.objects for insert with check(true);
      create policy legacy_update on storage.objects for update using(true) with check(true);
      create policy legacy_delete on storage.objects for delete using(true);`);
    await db.query('insert into auth.users values($1),($2)', [owner, other]);
    await db.query('insert into ladra.animales(id,creado_por,mostrar_en_red) values($1,$3,true),($2,$3,false)', [pet, privatePet, owner]);
    await db.exec(migration);
    await as('authenticated', owner);
    const id = await scalar("insert into ladra.publicaciones_feed(animal_id,tipo,texto) values($1,'post','Leia en el parque') returning id", [pet]);
    await db.query('update ladra.publicaciones_feed set texto=$2 where id=$1', [id, 'Texto corregido']);
    assert.equal(await scalar('select revision from ladra.publicaciones_feed where id=$1', [id]), 2);
    await assert.rejects(db.query('update ladra.publicaciones_feed set autor_id=$2 where id=$1', [id, other]), /permission denied/);
    await assert.rejects(db.query("insert into ladra.publicaciones_feed(animal_id,tipo,texto) values($1,'post','Privada')", [privatePet]), /row-level security/);
    await as('authenticated', other);
    assert.equal((await db.query("update ladra.publicaciones_feed set texto='Ajeno' where id=$1 returning id", [id])).rows.length, 0);
    assert.equal((await db.query('delete from ladra.publicaciones_feed where id=$1 returning id', [id])).rows.length, 0);
    await assert.rejects(db.query("insert into ladra.publicaciones_feed(animal_id,tipo,texto) values($1,'post','Suplantación')", [pet]), /row-level security/);
    await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('ladra-feed',$1)", [`${owner}/${pet}/foto.jpg`]), /row-level security/);
    await as('authenticated', owner);
    await db.query("insert into storage.objects(bucket_id,name) values('ladra-feed',$1)", [`${owner}/${pet}/foto.jpg`]);
    assert.equal((await db.query("update storage.objects set name='otra.jpg' where bucket_id='ladra-feed' returning id")).rows.length, 0);
    await as('authenticated', other);
    assert.equal((await db.query("delete from storage.objects where bucket_id='ladra-feed' returning id")).rows.length, 0);
    await db.exec('reset role');
    await db.query("insert into ladra.publicaciones_feed(animal_id,autor_id,tipo,texto,creado_en) values($1,$2,'historia','Antigua',now()-interval '25 hours'),($1,$2,'historia','Vigente',now())", [pet, owner]);
    await as('anon');
    assert.deepEqual((await db.query('select texto from ladra.publicaciones_feed order by texto')).rows.map(r => r.texto), ['Texto corregido', 'Vigente']);
    await assert.rejects(db.query("insert into ladra.publicaciones_feed(animal_id,tipo,texto) values($1,'post','Sin sesión')", [pet]), /permission denied/);
    await db.exec('reset role'); await db.query('update ladra.animales set mostrar_en_red=false where id=$1', [pet]);
    await as('anon'); assert.equal(await scalar('select count(*)::int from ladra.publicaciones_feed'), 0);
    await as('authenticated', owner);
    await db.exec("insert into storage.objects(bucket_id,name) values('otro-bucket','libre.jpg'); update storage.objects set name='otra.jpg' where bucket_id='otro-bucket'; delete from storage.objects where bucket_id='otro-bucket'");
  } finally { await db.close(); }
});
